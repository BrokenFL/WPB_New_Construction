import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { factOutputs, refreshReviewedFacts } from "./refresh-reviewed-building-facts.mjs";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { fileURLToPath } from "node:url";

async function fixture(t) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "reviewed-building-facts-"));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const file = path.join(root, factOutputs[0]);
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, "before");
  const input = path.join(root, "reviewed-input.json");
  await fs.writeFile(input, "preserve reviewed input");
  return { root, file, input };
}
test("failed propagation restores generated bytes and removes only newly generated output", async t => {
  const { root, file, input } = await fixture(t);
  let calls = 0;
  await assert.rejects(refreshReviewedFacts({ root, projects: ["example"], run: async () => {
    await fs.writeFile(file, "partial output");
    await fs.writeFile(path.join(root, factOutputs[1]), "new output");
    if (++calls === 2) throw new Error("generator failed");
  } }), /generator failed/);
  assert.equal(await fs.readFile(file, "utf8"), "before");
  await assert.rejects(fs.access(path.join(root, factOutputs[1])), { code: "ENOENT" });
  assert.equal(await fs.readFile(input, "utf8"), "preserve reviewed input");
});
test("check reports stale consumers without replacing existing working bytes", async t => {
  const { root, file } = await fixture(t);
  const result = await refreshReviewedFacts({ root, projects: ["example"], check: true, run: async () => fs.writeFile(file, "generated") });
  assert.equal(result.state, "stale");assert.equal(result.changed.length, 1);
  assert.notEqual(result.changed[0].beforeSha256, result.changed[0].afterSha256);
  assert.equal(await fs.readFile(file, "utf8"), "before");
});
test("identical propagation is a no-change and does not require a release", async t => {
  const { root } = await fixture(t);
  assert.deepEqual(await refreshReviewedFacts({ root, projects: ["example"], run: async () => {} }), { state: "no-change", projects: ["example"], changed: [], checked: false });
});

